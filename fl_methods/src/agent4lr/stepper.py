"""Per-API-call state machine for Agent4LR.

The sync runner (:mod:`src.agent4lr.agent`) and the batch workflow both
drive slot execution through the two functions here —
:func:`build_request` and :func:`apply_response` — so the transcript
construction (``input_list`` + human-readable ``messages``) has a single
implementation and cannot drift between the two paths.

One "step" is exactly one LLM API call plus its local consequences:

* **planner** — one step completes the slot.
* **tool_caller** — each step is one ReAct iteration: the deterministic
  ``"You have {remaining} tool calls remaining."`` reminder, the model
  response, local tool execution, and the appended observations. The
  slot completes on an ``exit`` call or budget exhaustion.
* **finisher** — one step: the deterministic handoff prompt, the model
  response, and extraction of the ``rank_methods`` indices.

Ephemeral pre-call messages (reminder/handoff) are regenerated by
:func:`build_request` and only persisted by :func:`apply_response`
together with the response items, so a :class:`PendingSlotState` never
holds a dangling prompt — resending a lost batch request is idempotent.

The state carried between steps is :class:`PendingSlotState`
(:mod:`src.agent4lr.checkpoints`); the sync runner keeps it in memory
only, while the batch workflow persists it between ticks.
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from dataclasses import dataclass, replace
from typing import Any

from src.agent4lr.agents import AgentSpec
from src.agent4lr.checkpoints import CompletedCheckpoint, PendingSlotState
from src.agent4lr.io import LRBugInputs
from src.agent4lr.prompts import (
    lr_finisher_user_prompt,
    lr_planner_user_prompt,
    lr_system_prompt,
    lr_tool_loop_user_prompt,
)
from src.agent4lr.providers import NormalisedResponse, ToolChoice
from src.agent4lr.tools import (
    LRToolContext,
    execute_tool,
    rank_methods,
    tool_schemas_finisher,
    tool_schemas_loop,
)

logger = logging.getLogger(__name__)

DEFAULT_TOOL_ITERATIONS = 10


@dataclass(frozen=True)
class PreparedRequest:
    """One ready-to-send LLM request for the slot a state is progressing.

    ``history`` is the canonical Responses-API-native input list
    *including* the regenerated ephemeral message (reminder/handoff)
    where the slot's role requires one. ``tools`` is in the nested shape
    emitted by :mod:`src.agent4lr.tools`, matching the ``Provider.chat``
    contract.
    """

    spec: AgentSpec
    history: list[dict[str, Any]]
    tools: list[dict[str, Any]] | None
    tool_choice: ToolChoice


@dataclass(frozen=True)
class AppliedStep:
    """Result of applying one response to a state.

    ``top5_indices`` is populated (possibly empty) only when a finisher
    slot completes; ``None`` otherwise.
    """

    state: PendingSlotState
    slot_completed: bool
    top5_indices: list[int] | None = None


def spec_from_identity(identity: dict[str, Any]) -> AgentSpec:
    """Reconstruct an :class:`AgentSpec` from its ``identity()`` dict."""
    return AgentSpec(**identity)


def tool_iter_budget(chain: Sequence[AgentSpec]) -> int:
    """Return the tool_caller slot's iteration budget for system-prompt rendering."""
    for spec in chain:
        if spec.role == "tool_caller" and spec.iterations is not None:
            return spec.iterations
    return DEFAULT_TOOL_ITERATIONS


def render_function_call_for_messages(name: str, arguments: dict[str, Any]) -> str:
    """Render a tool call as ``"[Function call: name(arg1, arg2)]"``.

    Matches FlexFL's ``process_response`` (``flexfl_pipeline.py:442``)
    so the human-readable transcript view stays byte-equivalent with
    the reference for matching tool-call arguments.
    """
    args_str = ", ".join(str(v) for v in arguments.values())
    return f"[Function call: {name}({args_str})]"


def extract_rank_methods_call(
    tool_calls: list[dict[str, Any]] | list[Any],
) -> list[int]:
    """Pull ``top_5_methods`` out of the finisher's structured tool call."""
    for tc in tool_calls:
        if tc.get("name") == "rank_methods":
            args = tc.get("arguments") or {}
            ids_raw = args.get("top_5_methods")
            if isinstance(ids_raw, list):
                out: list[int] = []
                for v in ids_raw:
                    if isinstance(v, bool):
                        continue
                    if isinstance(v, int):
                        out.append(v)
                    elif isinstance(v, float) and v.is_integer():
                        out.append(int(v))
                    elif isinstance(v, str):
                        try:
                            out.append(int(v.strip()))
                        except ValueError:
                            continue
                return out
    return []


