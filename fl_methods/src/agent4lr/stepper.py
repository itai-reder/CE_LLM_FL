# State construction
# ---------------------------------------------------------------------------


def initial_state(
    *,
    inputs_desc: dict[str, Any],
    inputs: LRBugInputs,
    chain: Sequence[AgentSpec],
) -> PendingSlotState:
    """Seed a fresh state at slot 0: system prompt + planner user prompt."""
    budget = tool_iter_budget(chain)
    system = lr_system_prompt(max_tool_calls=budget, inputs=inputs)
    user0 = lr_planner_user_prompt(inputs)
    seed = [
        {"role": "system", "content": system},
        {"role": "user", "content": user0},
    ]
    return PendingSlotState(
        inputs_descriptor=dict(inputs_desc),
        completed_chain=[],
        slot_spec=chain[0].identity(),
        calls_made=0,
        exited=False,
        input_list=[dict(m) for m in seed],
        messages=[dict(m) for m in seed],
        raw_responses=[],
    )


def state_for_slot(
    *,
    inputs_desc: dict[str, Any],
    chain: Sequence[AgentSpec],
    slot_index: int,
    ckpt: CompletedCheckpoint,
) -> PendingSlotState:
    """Fresh state for slot ``slot_index``, seeded from the previous slot's checkpoint.

    ``ckpt`` must be the completed checkpoint of ``chain[:slot_index]``.
    """
    return PendingSlotState(
        inputs_descriptor=dict(inputs_desc),
        completed_chain=[s.identity() for s in chain[:slot_index]],
        slot_spec=chain[slot_index].identity(),
        calls_made=0,
        exited=False,
        input_list=list(ckpt.input_list),
        messages=list(ckpt.messages),
        raw_responses=list(ckpt.raw_responses),
    )


