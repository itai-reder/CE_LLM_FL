# Step functions
# ---------------------------------------------------------------------------


def slot_is_complete(state: PendingSlotState) -> bool:
    """True when the state's slot needs no further LLM calls."""
    spec = spec_from_identity(state.slot_spec)
    if spec.role == "tool_caller":
        iters = spec.iterations or DEFAULT_TOOL_ITERATIONS
        return state.exited or state.calls_made >= iters
    return state.calls_made >= 1


def build_request(state: PendingSlotState) -> PreparedRequest:
    """Build the next LLM request for ``state``.

    Deterministic in the state: rebuilding after a lost/failed batch
    request yields a byte-identical request. Raises ``ValueError`` when
    the slot is already complete — callers must promote the state to a
    completed checkpoint instead.
    """
    if slot_is_complete(state):
        raise ValueError(
            f"build_request called on a completed slot "
            f"(role={state.slot_spec.get('role')!r}, calls_made={state.calls_made}, "
            f"exited={state.exited})"
        )
    spec = spec_from_identity(state.slot_spec)
    if spec.role == "planner":
        return PreparedRequest(
            spec=spec,
            history=list(state.input_list),
            tools=None,
            tool_choice="none",
        )
    if spec.role == "tool_caller":
        iters = spec.iterations or DEFAULT_TOOL_ITERATIONS
        reminder = {
            "role": "user",
            "content": lr_tool_loop_user_prompt(remaining=iters - state.calls_made),
        }
        return PreparedRequest(
            spec=spec,
            history=[*state.input_list, reminder],
            tools=tool_schemas_loop(),
            tool_choice="required",
        )
    if spec.role == "finisher":
        handoff = {"role": "user", "content": lr_finisher_user_prompt()}
        return PreparedRequest(
            spec=spec,
            history=[*state.input_list, handoff],
            tools=tool_schemas_finisher(),
            tool_choice="required",
        )
    raise ValueError(f"Unknown slot role {spec.role!r}")


def apply_response(
    state: PendingSlotState,
    resp: NormalisedResponse,
    ctx: LRToolContext,
) -> AppliedStep:
    """Apply one LLM response to ``state``: one complete step.

    Appends the same ephemeral message :func:`build_request` sent (so
    persisted transcripts stay byte-identical with the sync loop's),
    then the response items, the human-readable assistant mirror, and —
    for tool_caller steps — executes the returned tool calls locally and
    appends their observations.
    """
    if slot_is_complete(state):
        raise ValueError("apply_response called on a completed slot")
    spec = spec_from_identity(state.slot_spec)
    input_list = list(state.input_list)
    messages = list(state.messages)
    raw_responses = [*state.raw_responses, resp["raw"]]
    exited = state.exited
    top5_indices: list[int] | None = None

    if spec.role == "planner":
        input_list.extend(resp["new_items"])
        if resp["content"]:
            messages.append({"role": "assistant", "content": resp["content"]})
    elif spec.role == "tool_caller":
        iters = spec.iterations or DEFAULT_TOOL_ITERATIONS
        reminder = {
            "role": "user",
            "content": lr_tool_loop_user_prompt(remaining=iters - state.calls_made),
        }
        input_list.append(dict(reminder))
        messages.append(dict(reminder))
        input_list.extend(resp["new_items"])

        tcs = resp["tool_calls"]
        # Human-readable assistant entry: any text plus a
        # "[Function call: ...]" synthetic line per tool call.
        pieces: list[str] = []
        if resp["content"]:
            pieces.append(resp["content"])
        for tc in tcs:
            pieces.append(render_function_call_for_messages(tc["name"], tc["arguments"]))
        if pieces:
            messages.append({"role": "assistant", "content": "\n".join(pieces)})

        # A response with no tool calls still consumes the iteration.
        if tcs:
            for tc in tcs:
                tool_output = execute_tool(ctx=ctx, name=tc["name"], args=tc["arguments"])
                call_id = tc.get("call_id") or ""
                input_list.append(
                    {
                        "type": "function_call_output",
                        "call_id": call_id,
                        "output": tool_output,
                    }
                )
                messages.append({"role": "user", "content": tool_output})
            if any(tc["name"] == "exit" for tc in tcs):
                logger.debug(
                    "Agent4LR %s-%s: tool-loop exited at iteration %d/%d",
                    ctx.project,
                    ctx.bug_id,
                    state.calls_made + 1,
                    iters,
                )
                exited = True
        if not exited and state.calls_made + 1 >= iters:
            logger.debug("Agent4LR %s-%s: tool-loop budget exhausted", ctx.project, ctx.bug_id)
    elif spec.role == "finisher":
        handoff = {"role": "user", "content": lr_finisher_user_prompt()}
        input_list.append(dict(handoff))
        messages.append(dict(handoff))
        input_list.extend(resp["new_items"])

        tcs = resp["tool_calls"]
        top5_indices = extract_rank_methods_call(tcs)

        pieces = []
        if resp["content"]:
            pieces.append(resp["content"])
        for tc in tcs:
            pieces.append(render_function_call_for_messages(tc["name"], tc["arguments"]))
        if pieces:
            messages.append({"role": "assistant", "content": "\n".join(pieces)})

        if top5_indices:
            resolved = rank_methods(ctx=ctx, top_5_methods=top5_indices)
            top_n_block = "\n".join(f"Top_{i} : {fqn}" for i, fqn in enumerate(resolved, start=1))
            if top_n_block:
                messages.append({"role": "user", "content": top_n_block})
    else:  # pragma: no cover — validate_v1_invariant rules this out upstream
        raise ValueError(f"Unknown slot role {spec.role!r}")

    new_state = replace(
        state,
        calls_made=state.calls_made + 1,
        exited=exited,
        input_list=input_list,
        messages=messages,
        raw_responses=raw_responses,
    )
    return AppliedStep(
        state=new_state,
        slot_completed=slot_is_complete(new_state),
        top5_indices=top5_indices,
    )


